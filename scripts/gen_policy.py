#!/usr/bin/env python3
"""Generate policy artifacts from docs/memory_policies_for_LLM.md.

The policy file is the single source. Each rule has a marker line:

    <!-- rule:<id> [scope:common] [tools:a,b] summary:"<one line>" -->

``scope:common`` puts the summary in the MCP server instructions; ``tools:``
appends it to those tool descriptions. Every summary goes to the cheat sheet.

Usage: ``python scripts/gen_policy.py`` to write, ``--check`` to verify.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "docs" / "memory_policies_for_LLM.md"
PACKAGED = ROOT / "graph_memory_mcp" / "resources" / "memory_policies_for_LLM.md"
MODULE = ROOT / "graph_memory_mcp" / "resources" / "policy_generated.py"
CHEATSHEET = ROOT / "docs" / "memory_policy_cheatsheet.md"
BEGIN = "<!-- BEGIN GENERATED rules (scripts/gen_policy.py) -->"
END = "<!-- END GENERATED rules -->"

_MARKER = re.compile(r"^<!-- rule:(?P<id>[a-z0-9-]+)(?P<attrs>.*?) -->$")
_ATTR = re.compile(r'(\w+):(?:"([^"]*)"|(\S+))')


def parse_rules(text: str) -> list[dict]:
    rules, seen = [], set()
    for line in text.splitlines():
        m = _MARKER.match(line.strip())
        if not m:
            continue
        attrs = {k: q or b for k, q, b in _ATTR.findall(m["attrs"])}
        rid = m["id"]
        if rid in seen or not attrs.get("summary"):
            raise ValueError(f"rule {rid!r}: duplicate id or missing summary")
        seen.add(rid)
        rules.append(
            {
                "id": rid,
                "common": attrs.get("scope") == "common",
                "tools": [t for t in attrs.get("tools", "").split(",") if t],
                "summary": attrs["summary"],
            }
        )
    return rules


def _q(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def render_module(rules: list[dict]) -> str:
    common = [r["summary"] for r in rules if r["common"]]
    tools: dict[str, list[str]] = {}
    for r in rules:
        for t in r["tools"]:
            tools.setdefault(t, []).append(r["summary"])
    lines = [
        '"""Generated by scripts/gen_policy.py from docs/memory_policies_for_LLM.md.',
        "",
        "Do not edit by hand.",
        '"""',
        "",
        "COMMON_RULES: tuple[str, ...] = (",
        *[f"    {_q(s)}," for s in common],
        ")",
        "",
        "TOOL_RULES: dict[str, str] = {",
        *[f"    {_q(t)}: {_q(' '.join(v))}," for t, v in sorted(tools.items())],
        "}",
        "",
    ]
    return "\n".join(lines)


def render_cheatsheet(current: str, rules: list[dict]) -> str:
    body = "\n".join(f"{i}. {r['summary']}" for i, r in enumerate(rules, 1))
    head, sep, rest = current.partition(BEGIN)
    _, sep2, tail = rest.partition(END)
    if not (sep and sep2):
        raise ValueError(f"{CHEATSHEET} lacks {BEGIN} / {END}")
    return f"{head}{BEGIN}\n{body}\n{END}{tail}"


def outputs() -> dict[Path, str]:
    source = SOURCE.read_text(encoding="utf-8")
    rules = parse_rules(source)
    return {
        PACKAGED: source,
        MODULE: render_module(rules),
        CHEATSHEET: render_cheatsheet(CHEATSHEET.read_text(encoding="utf-8"), rules),
    }


def stale() -> list[Path]:
    return [
        p
        for p, text in outputs().items()
        if not p.is_file() or p.read_text(encoding="utf-8") != text
    ]


def main(argv: list[str]) -> int:
    if "--check" in argv:
        bad = stale()
        for p in bad:
            print(f"out of date: {p.relative_to(ROOT)} (run scripts/gen_policy.py)")
        return 1 if bad else 0
    for p, text in outputs().items():
        p.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
